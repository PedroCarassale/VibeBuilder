import { DEFAULT_ENTRY_POINT } from "./contract.js";

export function createMockArtifactSource({ prompt, previewUrl = null }) {
  const appTitle = prompt.trim().slice(0, 40) || "VibeBuilder App";
  const safePreviewUrl =
    typeof previewUrl === "string" && previewUrl.trim().length > 0
      ? previewUrl.trim()
      : `https://preview.v0.dev/mock-${Date.now()}`;

  return {
    type: "inline-files",
    generatorName: "mock-v0",
    generatorVersion: "1.0.0",
    previewUrl: safePreviewUrl,
    files: [
      {
        relativePath: "package.json",
        content: JSON.stringify(
          {
            name: "vibebuilder-mock-app",
            private: true,
            version: "0.0.1",
            type: "module",
            scripts: {
              dev: "vite",
              build: "tsc && vite build",
              preview: "vite preview"
            },
            dependencies: {
              react: "^18.3.1",
              "react-dom": "^18.3.1"
            },
            devDependencies: {
              typescript: "^5.6.3",
              vite: "^5.4.10",
              "@types/react": "^18.3.12",
              "@types/react-dom": "^18.3.1",
              "@vitejs/plugin-react": "^4.3.3"
            }
          },
          null,
          2
        )
      },
      {
        relativePath: "index.html",
        content: `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${appTitle}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/${DEFAULT_ENTRY_POINT}"></script>
  </body>
</html>
`
      },
      {
        relativePath: "vite.config.ts",
        content: `import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

export default defineConfig({
  plugins: [react()]
});
`
      },
      {
        relativePath: "tsconfig.json",
        content: JSON.stringify(
          {
            compilerOptions: {
              target: "ES2020",
              module: "ESNext",
              jsx: "react-jsx",
              moduleResolution: "Bundler",
              strict: true
            },
            include: ["src"]
          },
          null,
          2
        )
      },
      {
        relativePath: DEFAULT_ENTRY_POINT,
        content: `import React from "react";
import { createRoot } from "react-dom/client";
import { App } from "./App";

createRoot(document.getElementById("root")!).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>
);
`
      },
      {
        relativePath: "src/App.tsx",
        content: `export function App() {
  return (
    <main style={{ fontFamily: "system-ui", padding: "2rem" }}>
      <h1>${appTitle}</h1>
      <p>Mock artifact generated by VibeBuilder.</p>
    </main>
  );
}
`
      }
    ]
  };
}
